    public static LinkedHashMap<String,List<Recommendation>> group(List<Recommendation> recs) {
        LinkedHashMap<String,List<Recommendation>> out=new LinkedHashMap<>();
        for(String p:PROFILES) out.put(p,new ArrayList<>());
        for(Recommendation r:recs) {
            Set<String> groups=groupsFor(r.title);
            for(String p:groups) out.get(p).add(r);
        }
        return out;
    }

