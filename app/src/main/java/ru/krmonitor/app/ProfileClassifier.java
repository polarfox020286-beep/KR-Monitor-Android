    private static void addIf(Set<String> out,String text,String profile,String...keys) {
        for(String k:keys) {
            if(text.contains(k)) {
                out.add(profile);
                return;
            }
        }
    }

    private static void addWord(Set<String> out,String text,String profile,String...words) {
        for(String word:words) {
            String w=Pattern.quote(word.toLowerCase(Locale.ROOT).replace('ё','е'));
            if(Pattern.compile("(^|[^а-яa-z0-9])"+w+"([^а-яa-z0-9]|$)").matcher(text).find()) {
                out.add(profile);
                return;
            }
        }
    }

    private static String norm(String s) {
        return (s==null?"":s).toLowerCase(Locale.ROOT).replace('ё','е').replace('–','-').replace('—','-');
    }
